"""Navigation : geste ou bouton retour, fiches, onglets, recettes, messages « Voir ma liste », liens drive."""
import os, re, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from localisation import serve, new_page, check, FAIL, RENNES, wait_near
from playwright.sync_api import sync_playwright

def screen(page):
    return page.evaluate("() => [...document.querySelectorAll('.screen')].filter(s => !s.hidden).map(s => s.id.replace('screen-', '')).join()")
def dialogs(page):
    return page.evaluate("() => [...document.querySelectorAll('dialog')].filter(d => d.open).map(d => d.id).join()")
def back(page):
    page.go_back(wait_until='commit'); page.wait_for_timeout(350)

httpd, base = serve()
with sync_playwright() as p:
    b = p.chromium.launch()
    ctx, page, errs, _ = new_page(b, base, geo=RENNES, init={'rs2:search': {'store': 'near', 'rayon': 'en:ice-creams-and-sorbets', 'ran': False}})
    wait_near(page)
    print('1. Accueil')
    check('Comment ça marche' in page.inner_text('#intro') and page.locator('#intro .steps li').count() == 3, 'mode d\'emploi en 3 étapes')

    print('2. Retour : fiche produit')
    page.click('#quick [data-q="en:ice-creams-and-sorbets"]')
    page.wait_for_selector('#list li .name', timeout=20000)
    page.click('#list li [data-open] >> nth=0'); page.wait_for_selector('#sheet[open]')
    back(page)
    check(dialogs(page) == '' and screen(page) == 'search' and page.url.startswith(base), 'le retour ferme la fiche et reste dans l\'appli')
    page.click('#list li [data-open] >> nth=0'); page.wait_for_selector('#sheet[open]')
    page.click('#sheetClose'); page.wait_for_timeout(300)
    page.click('nav [data-go="list"]'); page.wait_for_timeout(200)
    back(page)
    check(screen(page) == 'search' and dialogs(page) == '', 'fermée avec ×, puis onglet : le retour revient à la recherche sans rouvrir la fiche')
    page.click('#list li [data-open] >> nth=0'); page.wait_for_selector('#sheet[open]')
    page.keyboard.press('Escape'); page.wait_for_timeout(300)
    page.click('nav [data-go="profile"]'); page.wait_for_timeout(200)
    back(page)
    check(screen(page) == 'search' and dialogs(page) == '', 'fermée avec Échap : historique cohérent')

    print('3. Retour : onglets')
    for t in ['list', 'recipes', 'profile']:
        page.click(f'nav [data-go="{t}"]'); page.wait_for_timeout(150)
    back(page); check(screen(page) == 'recipes', 'Profil → retour → Recettes')
    back(page); check(screen(page) == 'list', 'retour → Ma liste')

    print('4. Retour : recettes')
    page.click('nav [data-go="recipes"]'); page.wait_for_timeout(200)
    page.click('text=Pâtes bolognaise'); page.wait_for_selector('#recIngr li')
    page.wait_for_function("() => !document.querySelector('#recIngr .pending')", timeout=30000)
    page.click('#recIngr [data-rp] >> nth=0'); page.wait_for_selector('#sheet[open]')
    back(page)
    check(dialogs(page) == '' and not page.is_hidden('#recDetail'), 'fiche d\'un ingrédient fermée, la recette reste affichée')
    back(page)
    check(page.is_hidden('#recDetail') and page.is_visible('#recHome'), 'retour → liste des recettes')
    page.click('#recNew'); page.wait_for_timeout(200)
    check(page.is_visible('#recEditor'), 'éditeur ouvert')
    back(page)
    check(page.is_visible('#recHome') and page.is_hidden('#recEditor'), 'retour depuis l\'éditeur')
    page.click('text=Crêpes'); page.wait_for_selector('#recIngr li'); page.click('#recBack'); page.wait_for_timeout(300)
    check(page.is_visible('#recHome'), 'bouton « Recettes » en haut = retour')
    back(page)
    check(screen(page) != 'recipes' or page.is_visible('#recHome'), 'pas de retour vers la recette déjà fermée')

    print('5. « Voir ma liste » après un ajout')
    page.click('nav [data-go="search"]'); page.wait_for_timeout(200)
    page.click('#list li [data-open] >> nth=1'); page.wait_for_selector('#sheet[open]')
    page.click('#sheetBody [data-act="shop"]'); page.wait_for_selector('#toast.show .tact')
    check(page.inner_text('#toast .tact') == 'Voir ma liste', 'message avec l\'action « Voir ma liste »')
    page.click('#toast .tact'); page.wait_for_timeout(400)
    check(screen(page) == 'list' and dialogs(page) == '', 'fiche fermée, Ma liste affichée')
    check(page.is_visible('#listSum') and 'meilleur choix' in page.inner_text('#listSum'), 'résumé en tête de liste : ' + page.inner_text('#listSum').replace('\n', ' '))
    page.click('#listSum'); page.wait_for_timeout(300)
    check(dialogs(page) == 'driveSheet', 'le résumé ouvre « Ma liste chez … »')
    back(page); check(dialogs(page) == '' and screen(page) == 'list', 'retour : fiche du drive fermée')
    back(page); check(screen(page) == 'search', 'retour : revient à la recherche (la fiche produit a été remplacée)')

    print('6. Fiche « Stock au drive »')
    page.click('#list li [data-open] >> nth=0'); page.wait_for_selector('#sheet[open] .drivebtn')
    txt = page.inner_text('#sheet .card:has(.drives)')
    check('vérifie que c\'est bien' in txt, 'nom, marque et format à comparer')
    check('Voir le produit' in txt and ('Vu dans cette enseigne' in txt or 'Pas signalé' in txt), 'produit exact et présence dans l\'enseigne indiqués')
    hrefs = page.eval_on_selector_all('#sheet .drivebtn .dmain', 'els => els.map(e => e.href)')
    alts = page.eval_on_selector_all('#sheet .drivebtn .dalt', 'els => els.map(e => e.textContent)')
    check(any(re.search(r'carrefour\.fr/s\?q=\d{8,14}$', h) or re.search(r'e\.leclerc/recherche\?q=\d{8,14}$', h) for h in hrefs), 'Carrefour / Leclerc : recherche par code-barres')
    check(any('Pas le bon produit' in a for a in alts), 'lien de secours par nom')
    gi = page.evaluate("() => __RS.driveUrl({ code:'3017620422003', product_name:'Pâte à tartiner', brands:'Nutella' }, 'intermarche')")
    check(gi == 'https://www.google.com/search?q=3017620422003%20site%3Aintermarche.com', 'Intermarché : fiche retrouvée par Google avec le code-barres')
    gn = page.evaluate("() => __RS.driveUrl({ code:'12', product_name:'Pâte à tartiner', brands:'Nutella' }, 'carrefour')")
    check(gn == 'https://www.carrefour.fr/s?q=Nutella%20P%C3%A2te%20tartiner', 'code-barres invalide : recherche par nom')
    page.click('#sheetBody summary:has-text("Labels")'); page.wait_for_timeout(100)
    page.click('#sheetBody [data-act="fav"]'); page.wait_for_timeout(200)
    check(page.evaluate("() => document.querySelector('#sheetBody details.more').open"), 'section dépliée gardée après un ajout aux favoris')

    print('7. Site du drive qui bloque (vérification de sécurité)')
    ctx.grant_permissions(['clipboard-read', 'clipboard-write'], origin=base.rstrip('/'))
    page.click('#sheetBody .dhelp summary'); page.wait_for_timeout(100)
    htxt = page.inner_text('#sheetBody .dhelp')
    check('navigation privée' in htxt and 'VPN' in htxt, 'aide : navigation privée, VPN, bloqueur')
    btn = page.locator('#sheetBody .dhelp [data-copy] >> nth=0')
    url = btn.get_attribute('data-copy')
    raw = page.eval_on_selector_all('#sheet .drivebtn .dmain', 'els => els.map(e => e.getAttribute("href"))')
    check(url == raw[0] and page.locator('#sheetBody .dhelp [data-copy]').count() == len(raw), 'un bouton « Copier le lien » par enseigne, avec le même lien que le bouton principal')
    btn.click(); page.wait_for_selector('#toast.show')
    check(page.evaluate('() => navigator.clipboard.readText()') == url and 'Lien copié' in page.inner_text('#toast'), 'lien copié dans le presse-papiers')
    page.click('#sheetBody [data-act="fav"]'); page.wait_for_timeout(200)
    check(page.evaluate("() => document.querySelector('#sheetBody .dhelp').open"), 'aide toujours dépliée après une mise à jour de la fiche')

    print('8. Barre du bas et défilement')
    page.click('#sheetClose'); page.wait_for_timeout(300)
    def geo():
        return page.evaluate("""() => { const sc = document.getElementById('scroller'), nb = document.querySelector('.tabbar').getBoundingClientRect();
          return { doc: document.scrollingElement.scrollHeight - innerHeight, y: scrollY, bottom: nb.bottom, top: nb.top, h: innerHeight, sc: sc.scrollTop, max: sc.scrollHeight - sc.clientHeight }; }""")
    page.evaluate("() => { const sc = document.getElementById('scroller'); sc.scrollTop = sc.scrollHeight; window.scrollTo(0, 99999); }")
    page.wait_for_timeout(200)
    g = geo()
    check(g['doc'] <= 1 and g['y'] == 0, f"la page entière ne défile pas, seul le contenu défile (écart {g['doc']} px)")
    check(abs(g['bottom'] - g['h']) <= 1, f"barre d'onglets collée en bas de l'écran ({g['bottom']:.0f} / {g['h']})")
    check(g['sc'] > 1000 and g['sc'] >= g['max'] - 1, f"le contenu défile jusqu'en bas ({g['sc']:.0f} px)")
    sb = page.evaluate("() => document.getElementById('screen-search').getBoundingClientRect().bottom")
    check(sb <= g['top'] + 1, 'le bas de la page n\'est pas caché sous la barre')
    page.evaluate("() => { document.getElementById('scroller').scrollTop = 1500; }")
    page.click('nav [data-go="list"]'); page.wait_for_timeout(150)
    check(geo()['sc'] == 0, 'Ma liste s\'ouvre en haut')
    page.click('nav [data-go="search"]'); page.wait_for_timeout(150)
    check(abs(geo()['sc'] - 1500) <= 1, f"retour sur Rechercher : même position dans les résultats ({geo()['sc']:.0f} px)")
    page.click('nav [data-go="search"]'); page.wait_for_timeout(900)
    check(geo()['sc'] == 0, 'toucher l\'onglet déjà ouvert remonte en haut')
    page.evaluate("() => { document.getElementById('scroller').scrollTop = 900; }")
    page.click('#list li [data-add][aria-pressed="false"] >> nth=0')
    page.wait_for_selector('#toast.show')
    tb = page.locator('#toast').bounding_box()
    check(tb['y'] + tb['height'] <= geo()['top'], 'message affiché au-dessus de la barre d\'onglets')
    page.click('nav [data-go="recipes"]'); page.click('text=Crêpes'); page.wait_for_selector('#recIngr li')
    page.click('nav [data-go="recipes"]'); page.wait_for_timeout(400)
    check(page.is_visible('#recHome') and page.is_hidden('#recDetail'), 'Recettes déjà ouvert : revient à la liste des recettes')
    check(not errs, 'aucune erreur JavaScript' + (': ' + '; '.join(errs[:3]) if errs else ''))
    b.close()
httpd.shutdown()
print('\n' + ('TOUT EST OK' if not FAIL else f'{len(FAIL)} ÉCHEC(S)'))
sys.exit(1 if FAIL else 0)
